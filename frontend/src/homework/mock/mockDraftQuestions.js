const questionBase = ({
  question_id,
  question_type,
  area,
  target,
  review_label,
  prompt,
  correct_answer,
  choices,
  ...data
}) => ({
  question_id,
  question_type,
  unit_id: UNIT_ID,
  evaluation_skill: areaToSkill[area],
  internal_review_area: area,
  target_item: target,
  review_label: review_label ?? target,
  question: prompt,
  prompt,
  choices,
  correct_answer,
  error_type: `${area}_error`,
  ...data,
})

const vocabularyQuestion = (data) => questionBase({
  area: 'vocabulary_understanding',
  review_label: `${data.korean} / ${data.romanization}`,
  target: data.korean,
  english_choices: data.english_choices ?? data.choices,
  ...data,
})

const choiceQuestion = (data) => questionBase({
  english_meaning: data.english,
  ...data,
})

